// Bundles dist/ into a single self-contained Worker script (dist-worker/worker.js).
// This is the primary deploy target: the Cloudflare API connector can't upload Workers
// Static Assets, so pages are embedded in the script and /media/* is served from R2
// (binding MEDIA, see src/media.js). `wrangler deploy` (src/worker.js) is the alternative.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { join, relative, extname } from "node:path";

const TYPES = { ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".xml": "application/rss+xml; charset=utf-8", ".txt": "text/plain; charset=utf-8", ".svg": "image/svg+xml", ".ico": "image/x-icon", ".png": "image/png", ".jpg": "image/jpeg", ".webp": "image/webp" };
const files = {};
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else files["/" + relative("dist", p).split("\\").join("/")] = { t: TYPES[extname(p)] || "application/octet-stream", b: readFileSync(p).toString("base64") };
  }
})("dist");

const media = readFileSync("src/media.js", "utf8").replace(/^export /gm, "");
const worker = `// Generated by scripts/bundle-worker.mjs. Do not edit.
${media}
const FILES = ${JSON.stringify(files)};
const APEX = "willfletcher.me";
const dec = (b) => Uint8Array.from(atob(b), (c) => c.charCodeAt(0));
function resolve(path) {
  if (FILES[path] && !path.endsWith("/index.html")) return { file: FILES[path] };
  if (path.endsWith("/") && FILES[path + "index.html"]) return { file: FILES[path + "index.html"] };
  if (!path.endsWith("/") && FILES[path + "/index.html"]) return { redirect: path + "/" };
  if (path.endsWith("/index.html")) return { redirect: path.slice(0, -10) };
  return null;
}
export default {
  async fetch(req, env) {
    const url = new URL(req.url);
    if (url.hostname === "www." + APEX) { url.hostname = APEX; return Response.redirect(url.toString(), 301); }
    if (req.method !== "GET" && req.method !== "HEAD") return new Response("Method not allowed", { status: 405, headers: { allow: "GET, HEAD" } });
    let path = url.pathname; try { path = decodeURIComponent(path); } catch {}
    if (path.startsWith(MEDIA_PREFIX)) return serveMedia(req, env, path);
    const r = resolve(path);
    if (r && r.redirect) { url.pathname = r.redirect; return Response.redirect(url.toString(), 301); }
    const f = r ? r.file : FILES["/404.html"];
    const isHtml = f.t.startsWith("text/html");
    return new Response(req.method === "HEAD" ? null : dec(f.b), {
      status: r ? 200 : 404,
      headers: { "content-type": f.t, "cache-control": isHtml ? "public, max-age=0, must-revalidate" : "public, max-age=3600", "x-content-type-options": "nosniff" },
    });
  },
};
`;
mkdirSync("dist-worker", { recursive: true });
writeFileSync("dist-worker/worker.js", worker);
console.log(`Bundled ${Object.keys(files).length} file(s) into dist-worker/worker.js (${worker.length} bytes)`);
